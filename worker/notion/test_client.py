# create_page
# ---------------------------------------------------------------------------


@pytest.mark.asyncio
async def test_create_page_returns_page_id() -> None:
    """
    create_page must call pages.create with the correct parent/properties and
    return the page ID from the API response.
    """
    fake_page = {"id": "page-abc-123"}

    with patch("notion.client.Client") as MockClient, patch(
        "notion.client.asyncio.to_thread", new_callable=AsyncMock
    ) as mock_to_thread, patch(
        "notion.client.asyncio.sleep", new_callable=AsyncMock
    ) as mock_sleep:
        # asyncio.to_thread returns the fake page dict
        mock_to_thread.return_value = fake_page

        client = NotionClient(api_key="secret_test", database_id="db-xyz")
        page_id = await client.create_page(
            title="Test Title",
            platform="twitter",
            content="Some content here",
            properties={
                "composite_score": 0.85,
                "score_breakdown": "signal=5,timing=4",
                "generated_at": "2026-03-20T00:00:00+00:00",
                "topic_id": 42,
                "thesis_provided": True,
                "model_used": "claude-3-5-sonnet",
                "token_cost": 0.001,
            },
        )

    assert page_id == "page-abc-123"
    # to_thread must have been called (wraps the synchronous SDK call)
    mock_to_thread.assert_called_once()
    # Rate-limit sleep must fire exactly once
    mock_sleep.assert_awaited_once_with(0.4)


@pytest.mark.asyncio
async def test_create_page_raises_notion_write_error_on_failure() -> None:
    """
    If the Notion SDK raises any exception, create_page must wrap it as
    NotionWriteError and still apply the rate-limit delay.
    """
    with patch("notion.client.Client"), patch(
        "notion.client.asyncio.to_thread", new_callable=AsyncMock
    ) as mock_to_thread, patch(
        "notion.client.asyncio.sleep", new_callable=AsyncMock
    ) as mock_sleep:
        mock_to_thread.side_effect = RuntimeError("network error")

        client = NotionClient(api_key="secret_test", database_id="db-xyz")
        with pytest.raises(NotionWriteError, match="Failed to create Notion page"):
            await client.create_page(
                title="Bad Page",
                platform="linkedin",
                content="content",
                properties={},
            )

    # Rate-limit sleep must still fire even on failure (finally block)
    mock_sleep.assert_awaited_once_with(0.4)


