@pytest.mark.asyncio
async def test_rate_limiting_delay() -> None:
    """
    Both create_page and add_comment must each call asyncio.sleep(0.4) exactly
    once, even when called back-to-back.
    """
    fake_page = {"id": "page-rate-test"}

    with patch("notion.client.Client"), patch(
        "notion.client.asyncio.to_thread", new_callable=AsyncMock
    ) as mock_to_thread, patch(
        "notion.client.asyncio.sleep", new_callable=AsyncMock
    ) as mock_sleep:
        mock_to_thread.side_effect = [fake_page, None]

        client = NotionClient(api_key="secret_test", database_id="db-xyz")
        await client.create_page(
            title="Rate Test",
            platform="substack",
            content="content",
            properties={},
        )
        await client.add_comment(page_id="page-rate-test", comment_text="comment")

    assert mock_sleep.await_count == 2
    for call_args in mock_sleep.await_args_list:
        assert call_args.args == (0.4,)
