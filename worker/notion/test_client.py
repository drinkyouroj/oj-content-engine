"""
Tests for worker/notion/client.py.

Covers initialisation validation, page creation, comment creation, and rate-limit
delay behaviour. All Notion SDK calls are mocked so no real API credentials are
required.
"""

from __future__ import annotations

import asyncio
from unittest.mock import AsyncMock, MagicMock, patch

import pytest

from notion.client import NotionClient, NotionWriteError


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _make_client(api_key: str = "secret_test", database_id: str = "db-123") -> NotionClient:
    """Return a NotionClient with a mocked underlying SDK client."""
    with patch("notion.client.Client"):
        client = NotionClient(api_key=api_key, database_id=database_id)
    return client


